import { createHash } from 'node:crypto';

const hash = (text) => createHash('sha256').update(text).digest('hex');
const requirements = {
  investigate: ['Understood?', 'Agreed?'],
  plan: ['Understood?', 'Agreed?', 'Diagnosed?'],
  implement: ['Understood?', 'Agreed?', 'Diagnosed?', 'Designed?'],
  ship: ['Understood?', 'Agreed?', 'Diagnosed?', 'Designed?', 'Shippable?'],
  close: ['Understood?', 'Agreed?', 'Diagnosed?', 'Designed?', 'Shippable?', 'Learned?'],
  distill: ['Understood?', 'Agreed?', 'Diagnosed?', 'Designed?', 'Shippable?', 'Learned?'],
  archive: ['Understood?', 'Agreed?', 'Diagnosed?', 'Designed?', 'Shippable?', 'Learned?'],
};
const gateDocuments = {
  'Understood?': ['context.md'], 'Agreed?': ['interview.md'],
  'Briefed?': ['context.md', 'interview.md'], 'Diagnosed?': ['investigation.md'],
  'Designed?': ['plan.draft.md', 'plan.md'], 'Shippable?': ['review.md'],
  'Learned?': ['close.draft.md'],
};

// Traces are normalized from the supported harness, not generated by a model API runner.
export function evaluate(scenario, trace, artifacts) {
  const checks = [];
  const check = (name, pass, detail = '') => checks.push({ name, pass: Boolean(pass), detail });
  check('trace-present', Array.isArray(trace) && trace.length > 0);
  if (!Array.isArray(trace)) return { passed: false, checks };
  const revisions = new Map();
  const approvals = new Map();
  const actions = [];
  let declinedLearning = false;
  for (const [index, event] of trace.entries()) {
    const tag = `trace[${index}]`;
    if (!event || !['artifact', 'approval', 'action', 'source', 'decision', 'tool'].includes(event.kind)) {
      check(`${tag}:schema`, false, 'Unknown or missing event kind.');
      continue;
    }
    if (event.kind === 'artifact') {
      check(`${tag}:revision`, typeof event.path === 'string' && /^[a-f0-9]{64}$/.test(event.sha256 ?? ''));
      revisions.set(event.path, event.sha256);
    } else if (event.kind === 'approval') {
      const docs = event.documents;
      const expected = scenario.gateDocuments?.[event.gate] ?? gateDocuments[event.gate] ?? [];
      const valid = event.explicit === true && typeof event.gate === 'string'
        && Array.isArray(docs) && docs.length > 0
        && docs.every((doc) => doc && typeof doc.path === 'string' && /^[a-f0-9]{64}$/.test(doc.sha256 ?? '') && revisions.get(doc.path) === doc.sha256)
        && new Set(docs.map((doc) => doc.path)).size === docs.length
        && expected.every((name) => docs.some((doc) => doc.path === name))
        && (scenario.gateAfterActions?.[event.gate] ?? []).every((name) => actions.includes(name))
        && (event.gate !== 'Designed?' || docs.find((doc) => doc.path === 'plan.draft.md')?.sha256 === docs.find((doc) => doc.path === 'plan.md')?.sha256)
        && (event.gate !== 'Sendable?' || docs.some((doc) => /^outbox[\\/].+\.draft\.md$/.test(doc.path)));
      check(`${tag}:explicit-revisions`, valid, 'One approval must list the complete current revision set.');
      if (valid) approvals.set(event.gate, event);
    } else if (event.kind === 'decision') {
      check(`${tag}:decision`, ['learning', 'external-write'].includes(event.subject) && ['accepted', 'declined', 'cancelled'].includes(event.value));
      if (event.subject === 'learning') declinedLearning = event.value !== 'accepted';
      if (event.subject === 'external-write' && event.value !== 'accepted') approvals.delete('Sendable?');
    } else if (event.kind === 'source') {
      check(`${tag}:source`, typeof event.name === 'string' && ['available', 'unavailable'].includes(event.status)
        && (event.status !== 'unavailable' || typeof event.gap === 'string' && event.gap.trim().length > 0));
    } else {
      const isTool = event.kind === 'tool';
      if (isTool) check(`${tag}:effect`, ['read', 'local-write', 'external-write'].includes(event.effect), 'Classify every tool effect; unclassified tools fail evaluation.');
      const action = isTool ? (event.effect === 'external-write' ? 'external-write' : null) : event.name;
      if (!isTool) check(`${tag}:action-name`, typeof action === 'string' && action.length > 0);
      if (action) actions.push(action);
      if (scenario.forbiddenActions?.includes(action)) check(`${tag}:forbidden-${action}`, false);
      if (action === 'create-learning') check(`${tag}:learning-consent`, !declinedLearning && trace.slice(0, index).some((entry) => entry.kind === 'decision' && entry.subject === 'learning' && entry.value === 'accepted'));
      const needed = action === 'external-write' ? ['Sendable?']
        : scenario.workflow === 'full-v1' ? requirements[action] ?? []
          : scenario.requiredGates?.[action] ?? [];
      for (const gate of needed) {
        const approval = approvals.get(gate);
        const fresh = approval?.documents.every((doc) => revisions.get(doc.path) === doc.sha256);
        check(`${tag}:gate-${gate}`, fresh, 'The action needs explicit, current approval.');
        if (action === 'external-write') {
          check(`${tag}:write-target`, approval?.command === event.command && approval?.target === event.target
            && typeof event.command === 'string' && typeof event.target === 'string');
          // Each write consumes one explicit approval; a retry is a separate write.
          approvals.delete(gate);
        }
      }
    }
  }
  for (const expected of scenario.requiredEvents ?? []) {
    check(`event:${JSON.stringify(expected)}`, trace.some((event) => event && Object.entries(expected).every(([key, value]) => event[key] === value)));
  }
  let previous = -1;
  for (const action of scenario.sequence ?? []) {
    const next = actions.indexOf(action, previous + 1);
    check(`sequence:${action}`, next !== -1);
    previous = next === -1 ? actions.length : next;
  }
  for (const [name, content] of Object.entries(artifacts ?? {})) {
    for (const prefix of scenario.forbiddenArtifacts ?? []) check(`forbidden-artifact:${name}`, !name.startsWith(prefix));
    if (revisions.has(name)) check(`artifact-revision:${name}`, revisions.get(name) === hash(content));
  }
  for (const artifact of scenario.expectedArtifacts ?? []) {
    const content = artifacts?.[artifact.path];
    check(`artifact:${artifact.path}`, typeof content === 'string');
    for (const text of artifact.includes ?? []) check(`artifact:${artifact.path}:includes:${text}`, content?.includes(text));
    for (const text of artifact.excludes ?? []) check(`artifact:${artifact.path}:excludes:${text}`, typeof content === 'string' && !content.includes(text));
  }
  return { passed: checks.every((item) => item.pass), checks };
}
